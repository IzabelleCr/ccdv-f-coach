def main():
    out = Path(__file__).resolve().parent / "bank"
    out.mkdir(exist_ok=True)
    by = defaultdict(list)
    for x in Q:
        by[x["domain"]].append(x)
    for dom, items in by.items():
        with open(out / f"{dom}.jsonl", "w", encoding="utf-8") as f:
            for x in items:
                f.write(json.dumps(x, ensure_ascii=False) + "\n")
    print(f"{len(Q)} questões em {len(by)} arquivos")


if __name__ == "__main__":
    main()
